%% Local functions

function validateCormatMatrix( ...
    matrixData, ...
    sorting, ...
    conditionLabel, ...
    subjectIndex ...
)

    if ~ismatrix(matrixData) || ...
            size(matrixData, 1) ~= size(matrixData, 2)
        error( ...
            '%s matrix for subject %d is not square.', ...
            conditionLabel, ...
            subjectIndex ...
        );
    end

    if size(matrixData, 1) < max(sorting)
        error([ ...
            '%s matrix for subject %d contains fewer ROIs than ' ...
            'required by the sorting vector.' ...
        ], ...
            conditionLabel, ...
            subjectIndex ...
        );
    end
end


function [NBSmat, contrastLabel] = extractNBSMatrix( ...
    resNBS, ...
    numberOfROIs ...
)

    NBSmat = zeros(numberOfROIs);
    contrastLabel = 'no significant NBS component';

    if isfield(resNBS, 'CON_MAT2') && ...
            ~isempty(resNBS.CON_MAT2) && ...
            ~isempty(resNBS.CON_MAT2{1, 1})

        component = full(resNBS.CON_MAT2{1, 1});

        NBSmat = double((component + component') ~= 0);

        contrastLabel = ...
            '[-1 1] conditioning > control';

        return;
    end

    if isfield(resNBS, 'CON_MAT1') && ...
            ~isempty(resNBS.CON_MAT1) && ...
            ~isempty(resNBS.CON_MAT1{1, 1})

        component = full(resNBS.CON_MAT1{1, 1});

        NBSmat = component + component';

        contrastLabel = ...
            '[1 -1] control > conditioning';
    end
end


function writeLabeledMatrix( ...
    filePath, ...
    matrixData, ...
    labels ...
)

    labels = labels(:);
    numberOfLabels = numel(labels);

    if ~isequal( ...
            size(matrixData), ...
            [numberOfLabels, numberOfLabels] ...
        )
        error( ...
            'Matrix dimensions do not match ROI labels.' ...
        );
    end

    outputCell = cell( ...
        numberOfLabels + 1, ...
        numberOfLabels + 1 ...
    );

    outputCell(1, 2:end) = labels';
    outputCell(2:end, 1) = labels;
    outputCell(2:end, 2:end) = num2cell(matrixData);

    writecell(outputCell, filePath);
end
