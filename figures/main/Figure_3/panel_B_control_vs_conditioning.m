% Repository-adapted NBS analysis.
%
% Analysis: TPnoPuff
% Figure destination: Figure 3B
%
% This script:
%   1. Loads PRE (trials 11-40) and TEST (trials 81-120) cormats
%      for the control and conditioning cohorts.
%   2. Calculates within-animal TEST - PRE connectivity-change matrices.
%   3. Compares these change matrices between cohorts.
%   4. Runs the original NBS procedure.
%   5. Plots the edge-wise T-statistic matrix with NBS-significant
%      connections outlined.
%   6. Plots the NBS-thresholded schemaball.
%   7. Exports source data, design matrices, NBS input matrices and results.
%
% Expected repository structure:
%
% NoSeMaze-Connectomics/
% ├── figures/
% │   ├── main/Figure_3/panel_B_TPnoPuff_NBS_control_vs_conditioning.m
% │   └── supplement/Figure_S5/figure_S5_Odor_NBS_control_vs_conditioning.m
% │
% ├── data/processed/fMRI/Figure_3/
% │   ├── conditioning/
% │   │   ├── cormat_v11_TPnoPuff11to40.mat
% │   │   ├── cormat_v11_TPnoPuff81to120.mat
% │   │   └── roidata*.mat
% │   └── control/
% │       ├── cormat_v6_TPnoPuff11to40.mat
% │       ├── cormat_v6_TPnoPuff81to120.mat
% │       └── roidata*.mat
% │
% ├── src/matlab/
% │   ├── acl_NBS_intercept.m
% │   ├── lei_ttest2.m
% │   ├── schemaball.m
% │   ├── colormaps/myColormap_darkredgreen.mat
% │   └── NBS/input_files/
% │       ├── UI.mat
% │       ├── COG.txt
% │       └── nodeLabels.txt
% │
% └── results/main/Figure_3/Figure_3B/
%
