function hierarchy = prepareHierarchy(DS_info)
% Add hierarchy measures needed for Figure 5:
%   - Rank, with rank 1 = highest David's score
%   - fr_loser, fraction of losses within the hierarchy window

    hierarchy = DS_info;

    [~, sortedIndex] = sort( ...
        [hierarchy.DS], ...
        'descend' ...
    );

    [~, rank] = sort(sortedIndex);

    hierarchy.Rank = rank;

    lossCounts = sum( ...
        hierarchy.match_matrix, ...
        1 ...
    )';

    totalLosses = sum(lossCounts);

    if totalLosses == 0
        error('Hierarchy match_matrix contains zero total losses.');
    end

    hierarchy.fr_loser = lossCounts ./ totalLosses;
end


function values = getMetricVector(aucStructure, fieldName)
% Extract one subject-level global AUC metric as a column vector.

    if ~isfield(aucStructure, fieldName)
        error( ...
            'Metric field "%s" does not exist in auc_struc.', ...
            fieldName ...
        );
    end

    values = [aucStructure.(fieldName)];
    values = values(:);

    if ~isnumeric(values)
        error( ...
            'Metric field "%s" is not numeric.', ...
            fieldName ...
        );
    end

    if any(~isfinite(values))
        warning( ...
            'Metric field "%s" contains NaN/Inf values.', ...
            fieldName ...
        );
    end
end


function [qValues, significant] = bhFdrAdjustedP(pValues, alpha)
% Benjamini-Hochberg FDR-adjusted p-values across one predefined family.

    pValues = pValues(:);

    qValues = nan(size(pValues));
    significant = false(size(pValues));

    finiteMask = isfinite(pValues);

    if ~any(finiteMask)
        return;
    end

    pFinite = pValues(finiteMask);

    [sortedP, sortIndex] = sort(pFinite);
    m = numel(sortedP);

    adjustedSorted = sortedP .* m ./ (1:m)';

    for index = m-1:-1:1
        adjustedSorted(index) = min( ...
            adjustedSorted(index), ...
            adjustedSorted(index + 1) ...
        );
    end

    adjustedSorted = min(adjustedSorted, 1);

    adjustedFinite = nan(m, 1);
    adjustedFinite(sortIndex) = adjustedSorted;

    qValues(finiteMask) = adjustedFinite;
    significant(finiteMask) = adjustedFinite <= alpha;
end


