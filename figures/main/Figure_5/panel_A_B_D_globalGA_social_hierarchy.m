% panel_A_B_D_globalGA_social_hierarchy.m
% Jonathan Reinwald
%
% Reviewer-facing reproduction script for Figure 5A, 5B and 5D.
%
% Main displayed analyses:
%   Figure 5A: social rank vs Delta C
%   Figure 5B: social rank vs Delta L
%   Figure 5D: fraction of losses vs TEST-PRE changes in Delta C and Delta L
%
% FDR correction:
%   The manuscript reports raw Pearson-correlation p-values and applies
%   Benjamini-Hochberg FDR correction across the three predefined global
%   graph metrics:
%
%       g_delta_C
%       g_delta_L
%       g_swp
%
%   SWP is therefore included in the statistical correction families even
%   though it is not displayed as a main Figure 5 panel.
%
% For social rank, separate three-metric FDR families are defined for:
%   1. PRE correlations
%   2. TEST correlations
%   3. TEST-PRE change correlations
%
% For fraction of losses, Figure 5D uses one three-metric FDR family for
% TEST-PRE change correlations.
%
% Raw correlation p-values are shown in the figures. A dagger indicates
% that the corresponding result survives FDR correction across Delta C,
% Delta L and SWP.
%
% PRE  = TPnoPuff trials 11-40
% TEST = TPnoPuff trials 81-120
%
% Graph threshold range:
%   45-50%
%
% Only the conditioning cohort is used.
%
% Expected repository structure:
%
% NoSeMaze-Connectomics/
% ├── figures/main/Figure_5/
% │   └── panel_A_B_D_globalGA_social_hierarchy.m
% │
% ├── data/processed/NoSeMaze/
% │   ├── 01_General_Overview.xlsx
% │   ├── AnimalNumb_to_ID.mat
% │   └── tubetest/
% │       ├── NoSeMaze_1/
% │       │   ├── DS_info_AM1_day3to16_12mice_withChasingAndDoubleChasing_thresh10_td15tt2s.mat
% │       │   └── DS_info_AM1_day8to21_12mice_withChasingAndDoubleChasing_thresh10_td15tt2s.mat
% │       └── NoSeMaze_2/
% │           └── DS_info_AM2_day1to14_12mice_withChasingAndDoubleChasing_thresh10_td15tt2s.mat
% │
% ├── data/processed/fMRI/Figure_4/Figure_4C_E/conditioning/
% │   ├── auc_struc_TPnoPuff11to40_45to50_p.mat
% │   └── auc_struc_TPnoPuff81to120_45to50_p.mat
% │
% ├── src/matlab/
% │   └── helpers/
% │       └── docDataSrc.m          (optional; may also be elsewhere below src/matlab)
% │
% └── results/main/Figure_5/
%     ├── Figure_5A/
%     ├── Figure_5B/
%     └── Figure_5D/
%
% -------------------------------------------------------------------------

