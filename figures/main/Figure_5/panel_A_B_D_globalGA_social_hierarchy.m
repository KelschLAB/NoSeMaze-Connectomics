    mkdir(resultsBaseDir);
end

%% Reconstruct hierarchy measures

% Original workflow uses sheet 9.
T = readtable( ...
    generalOverviewFile, ...
    'Sheet', ...
    9, ...
    'ReadVariableNames', ...
    true, ...
    'VariableNamingRule', ...
    'modify' ...
);

tmp = load(am1EarlyFile, 'DS_info');
DS_AM1_early = prepareHierarchy(tmp.DS_info);

tmp = load(am1LateFile, 'DS_info');
DS_AM1_late = prepareHierarchy(tmp.DS_info);

tmp = load(am2File, 'DS_info');
DS_AM2 = prepareHierarchy(tmp.DS_info);

%% Build animal-wise behavioral information

info = struct;
counter = 0;

for rowIndex = 1:height(T)

    autonomouse = getNumericScalar(T.Autonomouse(rowIndex));

    if ~ismember(autonomouse, [1, 2])
        continue;
    end

    currentID = normalizeAnimalID(T.AnimalIDCombined(rowIndex));

    if autonomouse == 1

        daysValue = normalizeText(T.DaysToConsider(rowIndex));

        if contains(daysValue, '16')

            hierarchy = DS_AM1_early;
            scanWindow = "AM1_day3to16";

        elseif contains(daysValue, '21')

            hierarchy = DS_AM1_late;
            scanWindow = "AM1_day8to21";

        else

            error( ...
                'Could not assign AM1 hierarchy window for animal %s.', ...
                currentID ...
            );
        end

    else

        hierarchy = DS_AM2;
        scanWindow = "AM2_day1to14";
    end

    hierarchyIDs = strings(numel(hierarchy.ID), 1);

    for hierarchyIndex = 1:numel(hierarchy.ID)
        hierarchyIDs(hierarchyIndex) = normalizeAnimalID( ...
            hierarchy.ID(hierarchyIndex) ...
        );
    end

    animalIndex = find(hierarchyIDs == currentID);

    if isempty(animalIndex)
        error( ...
            'Animal ID %s was not found in the assigned hierarchy file.', ...
            currentID ...
        );
    end

    if numel(animalIndex) ~= 1
        error( ...
            'Animal ID %s occurs more than once in the hierarchy file.', ...
            currentID ...
        );
    end

    counter = counter + 1;

    info.ID(counter, 1) = currentID;
    info.NoSeMaze(counter, 1) = autonomouse;
    info.HierarchyWindow(counter, 1) = scanWindow;
    info.Rank(counter, 1) = hierarchy.Rank(animalIndex);
    info.FractionLosses(counter, 1) = hierarchy.fr_loser(animalIndex);
end

if counter == 0
    error('No NoSeMaze 1/2 animals were found in the General Overview.');
end

%% Map behavioral IDs to MRI animal numbers

mapLoaded = load(animalMapFile);

if ~isfield(mapLoaded, 'AnimalNumb_to_ID')
    error( ...
        'Variable "AnimalNumb_to_ID" missing from:\n%s', ...
        animalMapFile ...
    );
end

AnimalNumb_to_ID = mapLoaded.AnimalNumb_to_ID;

mapIDs = strings(numel(AnimalNumb_to_ID), 1);

for mapIndex = 1:numel(AnimalNumb_to_ID)
    mapIDs(mapIndex) = normalizeAnimalID( ...
        AnimalNumb_to_ID(mapIndex).ID ...
    );
end

animalNumbers = nan(counter, 1);

for animalIndex = 1:counter

    targetID = info.ID(animalIndex);
    mapMatch = find(mapIDs == targetID);

    if isempty(mapMatch)
        error( ...
            'Animal ID %s was not found in AnimalNumb_to_ID.', ...
            targetID ...
        );
    end

    mappedNumbers = nan(numel(mapMatch), 1);

    for matchIndex = 1:numel(mapMatch)
        mappedNumbers(matchIndex) = getNumericScalar( ...
            AnimalNumb_to_ID(mapMatch(matchIndex)).AnimalNumb ...
        );
    end

    uniqueMappedNumbers = unique(mappedNumbers);

    if numel(uniqueMappedNumbers) ~= 1
        error( ...
            'Animal ID %s maps to multiple AnimalNumb values: %s', ...
            targetID, ...
            mat2str(uniqueMappedNumbers') ...
        );
    end

    animalNumbers(animalIndex) = uniqueMappedNumbers;
end

[animalNumbersSorted, sortIndex] = sort(animalNumbers, 'ascend');

animalIDsSorted = info.ID(sortIndex);
noSeMazeSorted = info.NoSeMaze(sortIndex);
hierarchyWindowSorted = info.HierarchyWindow(sortIndex);

rankInput = info.Rank(sortIndex);
fractionLossesInput = info.FractionLosses(sortIndex);

%% Load graph metric AUC structures

preLoaded = load(aucPreFile);
testLoaded = load(aucTestFile);

if ~isfield(preLoaded, 'auc_struc')
    error('Variable "auc_struc" missing from PRE AUC file.');
end

if ~isfield(testLoaded, 'auc_struc')
    error('Variable "auc_struc" missing from TEST AUC file.');
end

aucPre = preLoaded.auc_struc;
aucTest = testLoaded.auc_struc;

%% Extract all three predefined graph metrics

metricPre = cell(numberOfMetrics, 1);
metricTest = cell(numberOfMetrics, 1);
metricDiff = cell(numberOfMetrics, 1);

numberOfGraphAnimals = [];

for metricIndex = 1:numberOfMetrics

    fieldName = metricInfo(metricIndex).fieldName;

    if ~isfield(aucPre, fieldName) || ~isfield(aucTest, fieldName)
        error( ...
            ['Required graph metric "%s" is missing from PRE or TEST AUC ' ...
             'file. All three metrics Delta C, Delta L and SWP are required ' ...
             'for the Figure 5 FDR correction.'], ...
            fieldName ...
        );
    end

    metricPre{metricIndex} = getMetricVector(aucPre, fieldName);
    metricTest{metricIndex} = getMetricVector(aucTest, fieldName);

    if numel(metricPre{metricIndex}) ~= numel(metricTest{metricIndex})
        error( ...
            '%s: PRE and TEST sample sizes differ.', ...
            fieldName ...
        );
    end

    metricDiff{metricIndex} = ...
        metricTest{metricIndex} - metricPre{metricIndex};

    if isempty(numberOfGraphAnimals)
        numberOfGraphAnimals = numel(metricPre{metricIndex});
    elseif numel(metricPre{metricIndex}) ~= numberOfGraphAnimals
        error('Global graph metric vectors have different sample sizes.');
    end
end

if numel(rankInput) ~= numberOfGraphAnimals
    error([ ...
        'Behavior/MRI sample-size mismatch: %d behavioral animals but ' ...
        '%d graph-analysis animals.' ...
    ], ...
        numel(rankInput), ...
        numberOfGraphAnimals ...
    );
end

fprintf('\nFigure 5 input check\n');
fprintf('Displayed graph threshold range: %d-%d%%\n', ...
    thresholdDisplayMin, thresholdDisplayMax);
fprintf('Animals: %d\n', numberOfGraphAnimals);
fprintf('FDR family: Delta C, Delta L, SWP\n\n');

%% Calculate Pearson correlations for all FDR families

rankPreR = nan(numberOfMetrics, 1);
rankPreP = nan(numberOfMetrics, 1);

rankTestR = nan(numberOfMetrics, 1);
rankTestP = nan(numberOfMetrics, 1);

rankDiffR = nan(numberOfMetrics, 1);
rankDiffP = nan(numberOfMetrics, 1);

lossDiffR = nan(numberOfMetrics, 1);
lossDiffP = nan(numberOfMetrics, 1);

for metricIndex = 1:numberOfMetrics

    [rankPreR(metricIndex), rankPreP(metricIndex)] = corr( ...
        rankInput, ...
        metricPre{metricIndex}, ...
        'Type', ...
        'Pearson', ...
        'Rows', ...
        'complete' ...
    );

    [rankTestR(metricIndex), rankTestP(metricIndex)] = corr( ...
        rankInput, ...
        metricTest{metricIndex}, ...
        'Type', ...
        'Pearson', ...
        'Rows', ...
        'complete' ...
    );

    [rankDiffR(metricIndex), rankDiffP(metricIndex)] = corr( ...
        rankInput, ...
        metricDiff{metricIndex}, ...
        'Type', ...
        'Pearson', ...
        'Rows', ...
        'complete' ...
    );

    [lossDiffR(metricIndex), lossDiffP(metricIndex)] = corr( ...
        fractionLossesInput, ...
        metricDiff{metricIndex}, ...
        'Type', ...
        'Pearson', ...
        'Rows', ...
        'complete' ...
    );
end

%% Benjamini-Hochberg FDR correction across Delta C, Delta L and SWP

[rankPreQ, rankPreFDR] = bhFdrAdjustedP(rankPreP, fdrAlpha);
[rankTestQ, rankTestFDR] = bhFdrAdjustedP(rankTestP, fdrAlpha);
[rankDiffQ, rankDiffFDR] = bhFdrAdjustedP(rankDiffP, fdrAlpha);

[lossDiffQ, lossDiffFDR] = bhFdrAdjustedP(lossDiffP, fdrAlpha);

%% Save combined FDR summary

summaryMetric = string({metricInfo.shortName})';
summaryField = string({metricInfo.fieldName})';

fdrSummary = table( ...
    summaryMetric, ...
    summaryField, ...
    rankPreR, ...
    rankPreP, ...
    rankPreQ, ...
    rankPreFDR, ...
    rankTestR, ...
    rankTestP, ...
    rankTestQ, ...
    rankTestFDR, ...
    rankDiffR, ...
    rankDiffP, ...
    rankDiffQ, ...
    rankDiffFDR, ...
    lossDiffR, ...
    lossDiffP, ...
    lossDiffQ, ...
    lossDiffFDR, ...
    'VariableNames', { ...
        'Metric'
        'AUC_Structure_Field'
        'Rank_PRE_R'
        'Rank_PRE_P_Raw'
        'Rank_PRE_FDR_Q'
        'Rank_PRE_FDR_Significant'
        'Rank_TEST_R'
        'Rank_TEST_P_Raw'
        'Rank_TEST_FDR_Q'
        'Rank_TEST_FDR_Significant'
        'Rank_Delta_R'
        'Rank_Delta_P_Raw'
        'Rank_Delta_FDR_Q'
        'Rank_Delta_FDR_Significant'
        'FractionLosses_Delta_R'
        'FractionLosses_Delta_P_Raw'
        'FractionLosses_Delta_FDR_Q'
        'FractionLosses_Delta_FDR_Significant'
    } ...
);

writetable( ...
    fdrSummary, ...
    fullfile( ...
        resultsBaseDir, ...
        'Figure_5_GlobalMetrics_FDR_Summary.csv' ...
    ) ...
);

%% Figure 5A and 5B: Rank vs Delta C / Delta L

for metricIndex = 1:2

    panelName = metricInfo(metricIndex).mainPanel;
    metricShortName = metricInfo(metricIndex).shortName;
    metricDisplayName = metricInfo(metricIndex).displayName;
    fieldName = metricInfo(metricIndex).fieldName;

    currentPre = metricPre{metricIndex};
    currentTest = metricTest{metricIndex};
    currentDiff = metricDiff{metricIndex};

    outputDir = fullfile(resultsBaseDir, panelName);

    if ~isfolder(outputDir)
        mkdir(outputDir);
    end

    fig = figure( ...
        'Name', ...
        sprintf('%s: Rank vs %s', panelName, metricShortName), ...
        'Visible', ...
        'on', ...
        'Color', ...
        'white', ...
        'Position', ...
        [100, 100, 900, 420] ...
    );

    %% Left: Rank vs PRE and TEST

    ax1 = subplot(1, 2, 1);
    hold(ax1, 'on');

    colorPre = [204/255, 51/255, 204/255];
    colorTest = [0, 160/255, 227/255];

    scPre = scatter( ...
        ax1, ...
        rankInput, ...
        currentPre, ...
        40, ...
        'filled' ...
    );

    scTest = scatter( ...
        ax1, ...
        rankInput, ...
        currentTest, ...
        40, ...
        'filled' ...
    );

    scPre.MarkerEdgeColor = 'none';
    scTest.MarkerEdgeColor = 'none';

    scPre.MarkerFaceColor = colorPre;
    scTest.MarkerFaceColor = colorTest;

    lineHandles = lsline(ax1);

    if numel(lineHandles) >= 2
        % lsline returns lines in reverse graphics order.
        lineHandles(1).Color = colorTest;
        lineHandles(1).LineWidth = 1.5;

        lineHandles(2).Color = colorPre;
        lineHandles(2).LineWidth = 1.5;
    end

    formatRankAxis(ax1, metricDisplayName);
    title(ax1, 'PRE and TEST', 'Interpreter', 'none');

    legend( ...
        ax1, ...
        [scPre, scTest], ...
