        'Location', ...
        'best', ...
        'Box', ...
        'off' ...
    );

    addTwoCorrelationAnnotations( ...
        ax1, ...
        rankPreR(metricIndex), ...
        rankPreP(metricIndex), ...
        rankPreFDR(metricIndex), ...
        rankTestR(metricIndex), ...
        rankTestP(metricIndex), ...
        rankTestFDR(metricIndex), ...
        colorPre, ...
        colorTest ...
    );

    %% Right: Rank vs TEST-PRE change

    ax2 = subplot(1, 2, 2);
    hold(ax2, 'on');

    colorDiff = (colorPre + colorTest) ./ 2;

    scDiff = scatter( ...
        ax2, ...
        rankInput, ...
        currentDiff, ...
        40, ...
        'filled' ...
    );

    scDiff.MarkerEdgeColor = 'none';
    scDiff.MarkerFaceColor = colorDiff;

    diffLine = lsline(ax2);

    if ~isempty(diffLine)
        diffLine(1).Color = colorDiff;
        diffLine(1).LineWidth = 1.5;
    end

    formatRankAxis( ...
        ax2, ...
        sprintf('%s | TEST - PRE', metricDisplayName) ...
    );

    title(ax2, 'TEST - PRE', 'Interpreter', 'none');

    addSingleCorrelationAnnotation( ...
        ax2, ...
        rankDiffR(metricIndex), ...
        rankDiffP(metricIndex), ...
        rankDiffFDR(metricIndex), ...
        colorDiff ...
    );

    sgtitle( ...
        sprintf('%s | social rank vs %s', panelName, metricDisplayName), ...
        'Interpreter', ...
        'tex' ...
    );

    %% Source data

    sourceData = table( ...
        animalIDsSorted, ...
        animalNumbersSorted, ...
        noSeMazeSorted, ...
        hierarchyWindowSorted, ...
        rankInput, ...
        currentPre, ...
        currentTest, ...
        currentDiff, ...
        'VariableNames', { ...
            'AnimalID'
            'AnimalNumber'
            'NoSeMaze'
            'HierarchyWindow'
            'Rank'
            'Pre'
            'Test'
            'Delta_TestMinusPre'
        } ...
    );

    writetable( ...
        sourceData, ...
        fullfile( ...
            outputDir, ...
            sprintf( ...
                'SourceData_%s_%s_Rank.csv', ...
                panelName, ...
                metricShortName ...
            ) ...
        ) ...
    );

    %% Statistics

    statisticsTable = table( ...
        ["Rank_vs_PRE"; "Rank_vs_TEST"; "Rank_vs_TESTminusPRE"], ...
        [ ...
            rankPreR(metricIndex)
            rankTestR(metricIndex)
            rankDiffR(metricIndex)
        ], ...
        [ ...
            rankPreP(metricIndex)
            rankTestP(metricIndex)
            rankDiffP(metricIndex)
        ], ...
        [ ...
            rankPreQ(metricIndex)
            rankTestQ(metricIndex)
            rankDiffQ(metricIndex)
        ], ...
        [ ...
            rankPreFDR(metricIndex)
            rankTestFDR(metricIndex)
            rankDiffFDR(metricIndex)
        ], ...
        'VariableNames', { ...
            'Comparison'
            'Pearson_R'
            'P_Raw'
            'FDR_Q'
            'FDR_Significant'
        } ...
    );

    writetable( ...
        statisticsTable, ...
        fullfile( ...
            outputDir, ...
            sprintf( ...
                'Statistics_%s_%s_Rank.csv', ...
                panelName, ...
                metricShortName ...
            ) ...
        ) ...
    );

    %% Complete result

    result = struct;

    result.Panel = panelName;
    result.Metric = metricShortName;
    result.FieldName = fieldName;

    result.AnimalID = animalIDsSorted;
    result.AnimalNumber = animalNumbersSorted;
    result.NoSeMaze = noSeMazeSorted;
    result.HierarchyWindow = hierarchyWindowSorted;
    result.Rank = rankInput;

    result.Pre = currentPre;
    result.Test = currentTest;
    result.Delta = currentDiff;

    result.Correlation.Pre.r = rankPreR(metricIndex);
    result.Correlation.Pre.pRaw = rankPreP(metricIndex);
    result.Correlation.Pre.qFDR = rankPreQ(metricIndex);
    result.Correlation.Pre.fdrSignificant = rankPreFDR(metricIndex);

    result.Correlation.Test.r = rankTestR(metricIndex);
    result.Correlation.Test.pRaw = rankTestP(metricIndex);
    result.Correlation.Test.qFDR = rankTestQ(metricIndex);
    result.Correlation.Test.fdrSignificant = rankTestFDR(metricIndex);

    result.Correlation.Delta.r = rankDiffR(metricIndex);
    result.Correlation.Delta.pRaw = rankDiffP(metricIndex);
    result.Correlation.Delta.qFDR = rankDiffQ(metricIndex);
    result.Correlation.Delta.fdrSignificant = rankDiffFDR(metricIndex);

    result.FDRFamily = {'g_delta_C', 'g_delta_L', 'g_swp'};
    result.FDRAlpha = fdrAlpha;

    save( ...
        fullfile( ...
            outputDir, ...
            sprintf( ...
                'Results_%s_%s_Rank.mat', ...
                panelName, ...
                metricShortName ...
            ) ...
        ), ...
        'result' ...
    );

    %% Metadata

    metadata = table( ...
        string(panelName), ...
        string(metricShortName), ...
        string(fieldName), ...
        thresholdDisplayMin, ...
        thresholdDisplayMax, ...
        numberOfGraphAnimals, ...
        fdrAlpha, ...
        string(generalOverviewFile), ...
        string(animalMapFile), ...
        string(aucPreFile), ...
        string(aucTestFile), ...
        'VariableNames', { ...
            'Panel'
            'Metric'
            'AUC_Structure_Field'
            'ThresholdDisplayMin'
            'ThresholdDisplayMax'
            'N'
            'FDR_Alpha'
            'GeneralOverviewFile'
            'AnimalMapFile'
            'AUC_Pre_File'
            'AUC_Test_File'
        } ...
    );

    writetable( ...
        metadata, ...
        fullfile( ...
            outputDir, ...
            sprintf( ...
                'AnalysisMetadata_%s_%s_Rank.csv', ...
                panelName, ...
                metricShortName ...
            ) ...
        ) ...
    );

    %% Optional source-script documentation

    if ~isempty(which('docDataSrc'))
        try
            docDataSrc(fig, outputDir, scriptFile, true);
        catch documentationError
            warning('docDataSrc failed: %s', documentationError.message);
        end
    end

    %% Export

    outputBaseName = sprintf( ...
        '%s_%s_Rank', ...
        panelName, ...
        metricShortName ...
    );

    exportgraphics( ...
        fig, ...
        fullfile(outputDir, [outputBaseName '.pdf']), ...
        'ContentType', ...
        'vector', ...
        'BackgroundColor', ...
        'white' ...
    );

    exportgraphics( ...
