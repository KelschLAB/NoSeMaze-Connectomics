metricInfo(2).mainPanel = 'Figure_5B';
metricInfo(2).displayInMainFigure = true;

metricInfo(3).shortName = 'SWP';
metricInfo(3).displayName = 'SWP';
metricInfo(3).fieldName = 'g_swp';
