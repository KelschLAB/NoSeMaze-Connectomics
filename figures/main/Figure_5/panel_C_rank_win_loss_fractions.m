%% Regression lines

lineHandles = lsline;

% lsline returns handles in reverse graphics order
if numel(lineHandles) >= 2

    lineHandles(1).Color = colorLosses;
    lineHandles(1).LineWidth = 1.5;

    lineHandles(2).Color = colorWins;
    lineHandles(2).LineWidth = 1.5;
end

