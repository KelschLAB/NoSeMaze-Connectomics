% panel_C_E_global_graph_metrics.m
% Jonathan Reinwald
%
% Repository-adapted analysis for Figure 4C-E.
%
% Figure 4C: Delta C (fractional deviation of clustering coefficient
%             from the lattice reference)
% Figure 4D: Delta L (fractional deviation of average shortest path
%             length from the random reference)
% Figure 4E: Small-world propensity (SWP)
%
% For each metric:
%   1. Conditioning cohort: PRE vs TEST
%   2. TEST-PRE change: conditioning vs control
%
% PRE  = TPnoPuff trials 11-40
% TEST = TPnoPuff trials 81-120
%
% Statistics:
%   - paired t-test + permutation_test_paired for conditioning PRE vs TEST
%   - unpaired t-test + permutation_test_unpaired for TEST-PRE change
%   - Benjamini-Hochberg FDR correction across Delta C, Delta L and SWP
%     separately for these two comparison families
%
% Raw permutation p-values are displayed in the figures. A dagger (†)
% is added when the corresponding permutation p-value survives FDR
% correction across Delta C, Delta L and SWP.
%
% Expected repository structure:
%
% NoSeMaze-Connectomics/
% ├── figures/main/Figure_4/
% │   └── panel_C_E_global_graph_metrics.m
% │
% ├── data/processed/fMRI/Figure_4/Figure_4C_E/
% │   ├── conditioning/
% │   │   ├── auc_struc_TPnoPuff11to40_45to50_p.mat
% │   │   └── auc_struc_TPnoPuff81to120_45to50_p.mat
% │   └── control/
% │       ├── auc_struc_TPnoPuff11to40_45to50_p.mat
% │       └── auc_struc_TPnoPuff81to120_45to50_p.mat
% │
% ├── src/matlab/
% │   ├── notBoxPlot_modified.m
% │   ├── permutation_test_paired.m
% │   ├── permutation_test_unpaired.m
% │   ├── sigstar.m
% │   └── docDataSrc.m              (optional)
% │
% └── results/main/Figure_4/
%     ├── Figure_4C/
%     ├── Figure_4D/
%     └── Figure_4E/
%
% Metric field names:
% Only the following three global metrics are analyzed:
%
%   Delta C : g_delta_C
%   Delta L : g_delta_L
%   SWP     : g_swp
%
% The script stops with an explicit error if any of these fields is
% missing from one of the four AUC input structures.
%
% -------------------------------------------------------------------------

