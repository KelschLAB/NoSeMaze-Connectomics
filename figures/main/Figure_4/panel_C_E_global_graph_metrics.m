    [~, ~, pValuesTask] = permutation_test_paired( ...
        preTask, ...
        testTask, ...
        numberOfPermutations, ...
        'mean' ...
    );

    rng(randomSeed, 'twister');

    [~, ~, pValuesDiff] = permutation_test_unpaired( ...
        diffTask, ...
        diffControl, ...
        numberOfPermutations, ...
        'mean' ...
    );

