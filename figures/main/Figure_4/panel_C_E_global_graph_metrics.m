    diffControl = testControl - preControl;

    %% Parametric tests retained from the original analysis

    [hTask, pTask, ~, statsTask] = ttest( ...
        preTask, ...
        testTask ...
    );

    [hDiff, pDiff, ~, statsDiff] = ttest2( ...
        diffTask, ...
        diffControl ...
    );

    %% Permutation tests retained as primary figure inference
    %
    % Conditioning PRE vs TEST: paired permutation test.
    % TEST-PRE conditioning vs control: unpaired permutation test.

