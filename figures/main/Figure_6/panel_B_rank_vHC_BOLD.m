end


function addDifferenceCorrelationText( ...
    ax, ...
    rPearson, ...
    pPearson, ...
    rSpearman, ...
    pSpearman, ...
    plotColor ...
)

    xLeft = ax.XLim(1) + 0.10*diff(ax.XLim);
    xRight = ax.XLim(1) + 0.55*diff(ax.XLim);

    y1 = ax.YLim(1) + 0.10*diff(ax.YLim);
    y2 = ax.YLim(1) + 0.20*diff(ax.YLim);

    text(ax, xLeft, y1, sprintf('p = %.3g', pPearson), ...
        'Color', plotColor, 'FontWeight', 'bold');

    text(ax, xRight, y1, sprintf('r = %.3f', rPearson), ...
        'Color', plotColor, 'FontWeight', 'bold');

    text(ax, xLeft, y2, sprintf('p_s = %.3g', pSpearman), ...
        'Color', plotColor, 'FontWeight', 'bold', 'Interpreter', 'tex');

    text(ax, xRight, y2, sprintf('\rho_s = %.3f', rSpearman), ...
        'Color', plotColor, 'FontWeight', 'bold', 'Interpreter', 'tex');
end
