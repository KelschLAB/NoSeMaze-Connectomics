% Standalone repository script for Figure 6B.
%
% Figure 6B relates social rank to mean vHC BOLD values extracted from
% the rank-related vHC cluster used in Figure 6A.
%
% Fixed analysis settings from the original script:
%   - explanatory variable: Rank only
%   - beta selection: vHC
%   - threshold: T01
%   - preprocessing: no scrubbing
%   - PRE  = TPnoPuff trials 11-40
%   - TEST = TPnoPuff trials 81-120
%
% The script plots:
%   1. PRE vs TEST mean BOLD
%   2. Rank vs PRE and TEST mean BOLD
%   3. Rank vs TEST-PRE BOLD change
%
% Pearson and Spearman correlations are reported.
% PRE vs TEST is additionally assessed with a paired t-test and
% 10,000-permutation paired test.
%
% Expected repository structure:
%
% NoSeMaze-Connectomics/
% ├── figures/main/Figure_6/
% │   └── panel_B_rank_vHC_BOLD.m
% │
% ├── data/processed/NoSeMaze/
% │   ├── 01_General_Overview.xlsx
% │   ├── AnimalNumb_to_ID.mat
% │   └── tubetest/
% │       ├── NoSeMaze_1/
% │       │   ├── DS_info_AM1_day3to16_12mice_withChasingAndDoubleChasing_thresh10_td15tt2s.mat
% │       │   └── DS_info_AM1_day8to21_12mice_withChasingAndDoubleChasing_thresh10_td15tt2s.mat
% │       └── NoSeMaze_2/
% │           └── DS_info_AM2_day1to14_12mice_withChasingAndDoubleChasing_thresh10_td15tt2s.mat
% │
% ├── data/processed/fMRI/Figure_6/Figure_6B/
