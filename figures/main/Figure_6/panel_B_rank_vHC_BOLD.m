function hierarchy = prepareHierarchy(DS_info)

    hierarchy = DS_info;

    [~, sortedIndex] = sort( ...
        [hierarchy.DS], ...
        'descend' ...
    );

    [~, rank] = sort(sortedIndex);

    hierarchy.Rank = rank;
end


function value = normalizeAnimalID(rawValue)

    while iscell(rawValue)
        if numel(rawValue) ~= 1
            error('Animal ID cell contains more than one element.');
        end
        rawValue = rawValue{1};
    end

    value = upper(strtrim(string(rawValue)));

    if numel(value) ~= 1 || ismissing(value) || strlength(value) == 0
        error('Could not convert an Animal ID to a valid string.');
    end
end


function value = normalizeText(rawValue)

    while iscell(rawValue)
        if numel(rawValue) ~= 1
            error('Text cell contains more than one element.');
        end
        rawValue = rawValue{1};
    end

    value = strtrim(string(rawValue));
end


function value = getNumericScalar(rawValue)

    while iscell(rawValue)
        if numel(rawValue) ~= 1
            error('Numeric cell contains more than one element.');
        end
        rawValue = rawValue{1};
    end

    if isnumeric(rawValue)
        value = double(rawValue);
    else
        value = str2double(string(rawValue));
    end

    if numel(value) ~= 1 || ~isfinite(value)
        error('Could not convert value to one finite numeric scalar.');
    end
end


function p = getScalarPermutationP(pValues)

    if isempty(pValues)
        p = NaN;
        return;
    end

    pValues = pValues(:);

    if numel(pValues) > 1
        warning([ ...
            'permutest returned %d p-values. ' ...
            'Using the smallest p-value for this scalar comparison.' ...
        ], numel(pValues));
    end

    p = min(pValues);
end


function addPreTestCorrelationText( ...
    ax, ...
    rPrePearson, ...
    pPrePearson, ...
    rPreSpearman, ...
    pPreSpearman, ...
    rTestPearson, ...
    pTestPearson, ...
    rTestSpearman, ...
    pTestSpearman ...
)

    preColor = [204/255, 51/255, 204/255];
    testColor = [0, 160/255, 227/255];

    xLeft = ax.XLim(1) + 0.10*diff(ax.XLim);
    xRight = ax.XLim(1) + 0.55*diff(ax.XLim);

    y1 = ax.YLim(1) + 0.10*diff(ax.YLim);
    y2 = ax.YLim(1) + 0.20*diff(ax.YLim);
    y3 = ax.YLim(1) + 0.90*diff(ax.YLim);
    y4 = ax.YLim(1) + 0.80*diff(ax.YLim);

    text(ax, xLeft, y1, sprintf('p = %.3g', pPrePearson), ...
        'Color', preColor, 'FontWeight', 'bold');
    text(ax, xRight, y1, sprintf('r = %.3f', rPrePearson), ...
        'Color', preColor, 'FontWeight', 'bold');

    text(ax, xLeft, y2, sprintf('p = %.3g', pTestPearson), ...
        'Color', testColor, 'FontWeight', 'bold');
    text(ax, xRight, y2, sprintf('r = %.3f', rTestPearson), ...
        'Color', testColor, 'FontWeight', 'bold');

    text(ax, xLeft, y3, sprintf('p_s = %.3g', pPreSpearman), ...
        'Color', preColor, 'FontWeight', 'bold', 'Interpreter', 'tex');
