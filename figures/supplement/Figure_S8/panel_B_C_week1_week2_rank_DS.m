function S = loadDSInfo(fileName)

    tmp = load(fileName,'DS_info');

    if ~isfield(tmp,'DS_info')
        error( ...
            'File %s does not contain variable DS_info.', ...
            fileName ...
        );
    end

    DS_info = tmp.DS_info;

    if ~isfield(DS_info,'DS')
        error( ...
            'DS_info in %s does not contain field DS.', ...
            fileName ...
        );
    end

    % Historical files may contain an explicit rank field. If not,
    % reconstruct the same ordinal rank from David's score:
    % rank 1 = highest David's score.
    if isfield(DS_info,'rank')

        rank = [DS_info.rank]';

    elseif isfield(DS_info,'Rank')

        rank = [DS_info.Rank]';

    else

        DS = [DS_info.DS]';

        [~,sortedIndex] = sort( ...
            DS, ...
            'descend' ...
        );

        [~,rank] = sort(sortedIndex);
        rank = rank(:);
    end

    S.rank = rank(:);
    S.DS = [DS_info.DS]';
end


function plotCorrelationPanel( ...
    ax, ...
    x, ...
    y, ...
    corrType, ...
    plotTitle, ...
    xLabel, ...
    yLabel ...
)

    hold(ax,'on');

    markerSize = 70;
    markerColor = [0.35,0.35,0.35];

    scatter( ...
        ax, ...
        x, ...
        y, ...
        markerSize, ...
        'filled', ...
        'MarkerFaceColor',markerColor, ...
        'MarkerEdgeColor','none', ...
        'MarkerFaceAlpha',0.85 ...
    );

    valid = isfinite(x) & isfinite(y);

    xv = x(valid);
    yv = y(valid);

    [r,p] = corr( ...
        xv, ...
        yv, ...
        'Rows','complete', ...
        'Type',corrType ...
    );

    allVals = [xv;yv];

    minVal = min(allVals);
    maxVal = max(allVals);

    pad = 0.08*range(allVals);

    if pad == 0 || isnan(pad)
        pad = 1;
    end

    lims = [
        minVal - pad
        maxVal + pad
    ];

    xlim(ax,lims);
    ylim(ax,lims);

    % Identity line
    plot( ...
        ax, ...
        lims, ...
        lims, ...
        'k:', ...
        'LineWidth',1.25, ...
        'HandleVisibility','off' ...
    );

    % Linear fit retained from original plot
    if numel(xv) > 1

        coeff = polyfit(xv,yv,1);

        xx = linspace(lims(1),lims(2),100);
        yy = polyval(coeff,xx);

        plot( ...
            ax, ...
            xx, ...
            yy, ...
            'k-', ...
            'LineWidth',1.75, ...
            'HandleVisibility','off' ...
        );
    end

    % Stats annotation
    statsText = sprintf( ...
        '%s r = %.2f\np = %s\nn = %d', ...
        corrType, ...
        r, ...
        formatPValue(p), ...
        numel(xv) ...
    );

    text( ...
        ax, ...
        0.05, ...
        0.95, ...
        statsText, ...
        'Units','normalized', ...
        'VerticalAlignment','top', ...
        'HorizontalAlignment','left', ...
        'FontSize',11, ...
        'FontWeight','bold', ...
        'BackgroundColor','white', ...
        'EdgeColor',[0.75,0.75,0.75], ...
        'Margin',6 ...
    );

    title( ...
        ax, ...
        plotTitle, ...
        'FontSize',13, ...
        'FontWeight','bold' ...
    );

    xlabel(ax,xLabel,'FontSize',11);
    ylabel(ax,yLabel,'FontSize',11);

    axis(ax,'square');
    grid(ax,'on');
    box(ax,'off');

    ax.FontSize = 10;
    ax.LineWidth = 1;
    ax.TickDir = 'out';

    hold(ax,'off');
end


function pText = formatPValue(p)

    if p < 0.001
        pText = '< 0.001';
    else
        pText = sprintf('%.3f',p);
    end
end


function rel = makeRepoRelative(pathString,repoRoot)

    p = strrep(char(pathString),'\','/');
    r = strrep(char(repoRoot),'\','/');

    if startsWith(lower(p),lower(r))

        rel = extractAfter( ...
            string(p), ...
            strlength(r) ...
        );

        rel = regexprep(rel,'^[\\/]+','');

    else

        rel = string(p);
    end
end
