    compose("AM1-%02d",(1:numel(NM1_rank_w1))')
    compose("AM2-%02d",(1:numel(NM2_rank_w1))')
];

%% Statistics

validRank = isfinite(rank_w1) & isfinite(rank_w2);

[rRank,pRank] = corr( ...
    rank_w1(validRank), ...
    rank_w2(validRank), ...
    'Rows','complete', ...
    'Type',rankCorrType ...
);

validDS = isfinite(DS_w1_z) & isfinite(DS_w2_z);

[rDS,pDS] = corr( ...
    DS_w1_z(validDS), ...
    DS_w2_z(validDS), ...
    'Rows','complete', ...
    'Type',DSCorrType ...
);

fprintf('\nSupplementary Figure S8B-C\n');
