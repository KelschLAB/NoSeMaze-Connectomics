%% Load hierarchy data

NM1_W1 = loadDSInfo(NM1_week1_file);
NM1_W2 = loadDSInfo(NM1_week2_file);

NM2_W1 = loadDSInfo(NM2_week1_file);
NM2_W2 = loadDSInfo(NM2_week2_file);

%% Assemble paired data

NM1_rank_w1 = NM1_W1.rank(:);
NM1_rank_w2 = NM1_W2.rank(:);

NM2_rank_w1 = NM2_W1.rank(:);
NM2_rank_w2 = NM2_W2.rank(:);

NM1_DS_w1 = NM1_W1.DS(:);
NM1_DS_w2 = NM1_W2.DS(:);

NM2_DS_w1 = NM2_W1.DS(:);
NM2_DS_w2 = NM2_W2.DS(:);

%% Basic checks

assert( ...
    numel(NM1_rank_w1) == numel(NM1_rank_w2), ...
    'NM1 rank vectors have different lengths.' ...
);

assert( ...
    numel(NM2_rank_w1) == numel(NM2_rank_w2), ...
    'NM2 rank vectors have different lengths.' ...
);

assert( ...
    numel(NM1_DS_w1) == numel(NM1_DS_w2), ...
    'NM1 David''s score vectors have different lengths.' ...
);

assert( ...
    numel(NM2_DS_w1) == numel(NM2_DS_w2), ...
    'NM2 David''s score vectors have different lengths.' ...
);

%% Combine cohorts

rank_w1 = [
    NM1_rank_w1
    NM2_rank_w1
];

rank_w2 = [
    NM1_rank_w2
    NM2_rank_w2
];

DS_w1_raw = [
    NM1_DS_w1
    NM2_DS_w1
];

DS_w2_raw = [
    NM1_DS_w2
    NM2_DS_w2
];

%% Z-score David's score within each NoSeMaze cohort and week

NM1_DS_w1_z = zscore(NM1_DS_w1);
NM1_DS_w2_z = zscore(NM1_DS_w2);

NM2_DS_w1_z = zscore(NM2_DS_w1);
NM2_DS_w2_z = zscore(NM2_DS_w2);

DS_w1_z = [
    NM1_DS_w1_z
    NM2_DS_w1_z
];

DS_w2_z = [
    NM1_DS_w2_z
    NM2_DS_w2_z
];

