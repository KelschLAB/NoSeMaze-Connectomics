% panel_B_week1_week2_rank_DS.m
% Jonathan Reinwald
%
% Supplementary Figure S8B-C
%
% Week-to-week stability of social hierarchy measures across NoSeMaze 1
% and NoSeMaze 2.
%
% Revised panel mapping:
%   Figure S8B: David's score, Week 1 vs Week 2, z-scored within cohort/week
%   Figure S8C: NoSeMaze rank, Week 1 vs Week 2
%
% Correlations retained from the original analysis:
%   - Rank: Spearman
%   - David's score: Pearson on cohort-wise z-scored values
%
% All animals are shown with identical markers; no point labels or cohort colors.
%
% Expected repository structure:
%
% NoSeMaze-Connectomics/
% ├── figures/supplement/Figure_S8/
% │   └── panel_B_week1_week2_rank_DS.m
% │
% ├── data/processed/NoSeMaze/tubetest/
% │   ├── NoSeMaze_1/
% │   │   ├── DS_info_AM1_day3to9_12mice_withChasingAndDoubleChasing_thresh10_td15tt2s.mat
% │   │   └── DS_info_AM1_day10to16_12mice_withChasingAndDoubleChasing_thresh10_td15tt2s.mat
% │   └── NoSeMaze_2/
% │       ├── DS_info_AM2_day1to7_12mice_withChasingAndDoubleChasing_thresh10_td15tt2s.mat
% │       └── DS_info_AM2_day8to14_12mice_withChasingAndDoubleChasing_thresh10_td15tt2s.mat
% │
% └── results/supplement/Figure_S8/Figure_S8B_C/
%
% Optional helper:
%   src/matlab/.../docDataSrc.m
%
% -------------------------------------------------------------------------

clear;
clc;
close all;

%% Settings

rankCorrType = 'Spearman';
DSCorrType   = 'Pearson';

%% Locate repository root

scriptFile = mfilename('fullpath');

if isempty(scriptFile)
    error([ ...
        'MATLAB could not determine the location of this script. ' ...
        'Run the complete saved script rather than selected lines.' ...
    ]);
end

scriptDir = fileparts(scriptFile);

% repo/figures/supplement/Figure_S8/panel_B_week1_week2_rank_DS.m
repoRoot = fileparts(fileparts(fileparts(scriptDir)));

%% Repository-relative paths

srcDir = fullfile(repoRoot,'src','matlab');

if isfolder(srcDir)
    addpath(genpath(srcDir));
end

noSeMazeDir = fullfile( ...
    repoRoot, ...
    'data','processed','NoSeMaze','tubetest' ...
);

nm1Dir = fullfile(noSeMazeDir,'NoSeMaze_1');
nm2Dir = fullfile(noSeMazeDir,'NoSeMaze_2');

outputDir = fullfile( ...
    repoRoot, ...
    'results','supplement', ...
    'Figure_S8','Figure_S8B_C' ...
);

if ~isfolder(outputDir)
    mkdir(outputDir);
end

%% Input files

NM1_week1_file = fullfile( ...
    nm1Dir, ...
    'DS_info_AM1_day3to9_12mice_withChasingAndDoubleChasing_thresh10_td15tt2s.mat' ...
);

NM1_week2_file = fullfile( ...
    nm1Dir, ...
    'DS_info_AM1_day10to16_12mice_withChasingAndDoubleChasing_thresh10_td15tt2s.mat' ...
);

NM2_week1_file = fullfile( ...
    nm2Dir, ...
    'DS_info_AM2_day1to7_12mice_withChasingAndDoubleChasing_thresh10_td15tt2s.mat' ...
);

NM2_week2_file = fullfile( ...
    nm2Dir, ...
    'DS_info_AM2_day8to14_12mice_withChasingAndDoubleChasing_thresh10_td15tt2s.mat' ...
);

requiredFiles = {
    NM1_week1_file
    NM1_week2_file
    NM2_week1_file
    NM2_week2_file
};

missingFiles = requiredFiles(~cellfun(@isfile,requiredFiles));

if ~isempty(missingFiles)
    error( ...
        'Required Figure S8B-C input files are missing:\n\n%s', ...
        strjoin(missingFiles,newline) ...
    );
end

if isempty(ver('stats'))
    error([ ...
        'Statistics and Machine Learning Toolbox is required ' ...
        'for corr and zscore.' ...
    ]);
