    );

    testTable = addvars( ...
        testTable, ...
        (1:results(roiIndex).numberOfSubjects)', ...
        'Before', ...
        1, ...
        'NewVariableNames', ...
        'SubjectIndex' ...
    );

    writetable( ...
        preTable, ...
        fullfile( ...
            outputDir, ...
            sprintf( ...
                'SourceData_Figure_S2B_%s_PRE_subjects.csv', ...
                roiName ...
            ) ...
        ) ...
    );

    writetable( ...
        testTable, ...
        fullfile( ...
            outputDir, ...
            sprintf( ...
                'SourceData_Figure_S2B_%s_TEST_subjects.csv', ...
                roiName ...
            ) ...
        ) ...
    );
end

