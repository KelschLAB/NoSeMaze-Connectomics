%% ========================================================================
% Local functions
%% ========================================================================

function semValues = semAcrossSubjects(subjectByTime)

    n = sum( ...
        isfinite(subjectByTime), ...
        1 ...
    );

    semValues = std( ...
        subjectByTime, ...
        0, ...
        1, ...
        'omitnan' ...
    ) ./ sqrt(n);

    semValues(n < 2) = NaN;
end


function lineHandle = plotMeanSem( ...
    ax, ...
    x, ...
    meanValues, ...
    semValues, ...
    lineColor, ...
    alphaValue, ...
    lineWidth ...
)

    x = x(:);
    meanValues = meanValues(:);
    semValues = semValues(:);

    lower = ...
        meanValues - semValues;

    upper = ...
        meanValues + semValues;

    patchHandle = fill( ...
        ax, ...
        [x; flipud(x)], ...
        [lower; flipud(upper)], ...
        lineColor, ...
        'FaceAlpha', ...
        alphaValue, ...
        'EdgeColor', ...
        'none' ...
    );

    patchHandle.HandleVisibility = 'off';

    lineHandle = plot( ...
        ax, ...
        x, ...
        meanValues, ...
        'Color', ...
        lineColor, ...
        'LineWidth', ...
        lineWidth ...
    );
end
