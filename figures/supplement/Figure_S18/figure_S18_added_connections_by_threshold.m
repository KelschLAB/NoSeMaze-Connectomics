function values = collectThresholdValues(gstruc,thresholdIndices)

    values = cell(1,numel(thresholdIndices));

    for k = 1:numel(thresholdIndices)

        thresholdIndex = thresholdIndices(k);

        currentValues = [];

        for subjectIndex = 1:size(gstruc,2)

            currentMatrix = ...
                gstruc(thresholdIndex,subjectIndex).o_CIJ_thresh;

            currentValues = [
                currentValues
                currentMatrix(:)
            ]; %#ok<AGROW>
        end

        values{k} = currentValues;
    end
end


function validateHistogramEdges(handles,label)

    reference = handles(1).BinEdges;

    for k = 2:numel(handles)

        if ~isequal(handles(k).BinEdges,reference)
            error( ...
                ['Histogram bin edges differ across thresholds for %s. ' ...
                 'Cannot reproduce original bin-count subtraction safely.'], ...
                label ...
            );
        end
    end
end


function counts = getHistogramCounts(handles)

    nBins = numel(handles(1).BinCounts);
    nThresholds = numel(handles);

    counts = nan(nBins,nThresholds);

    for k = 1:nThresholds
        counts(:,k) = handles(k).BinCounts';
    end
end


function writeHistogramSourceData(edges,counts,thresholdLabels,outputFile)

    sourceData = table( ...
        edges(1:end-1)', ...
        edges(2:end)', ...
        'VariableNames',{'edge_from','edge_to'} ...
    );

    for k = 1:numel(thresholdLabels)

        variableName = sprintf('count_%d',thresholdLabels(k));
        sourceData.(variableName) = counts(:,k);
    end

    writetable(sourceData,outputFile);
end

function writeAddedConnectionsSourceData(edges,counts,outputFile)

    sourceData = table( ...
        edges(1:end-1)', ...
        edges(2:end)', ...
        counts', ...
        'VariableNames',{'edge_from','edge_to','count_added'} ...
    );

    writetable(sourceData,outputFile);
end

function rel = makeRepoRelative(pathString,repoRoot)

    p = strrep(char(pathString),'\','/');
    r = strrep(char(repoRoot),'\','/');

    if startsWith(lower(p),lower(r))
        rel = extractAfter(string(p),strlength(r));
        rel = regexprep(rel,'^[\\/]+','');
    else
        rel = string(p);
    end
end

