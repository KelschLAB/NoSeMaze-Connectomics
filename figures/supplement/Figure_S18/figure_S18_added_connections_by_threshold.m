    % Control PRE
    histogram( ...
        'BinCounts',addedControlPre{intervalIndex}, ...
        'BinEdges',controlPreEdges, ...
        'EdgeColor','none', ...
        'FaceColor',controlPreColor, ...
        'FaceAlpha',0.1, ...
        'LineWidth',1.5, ...
        'LineStyle',':' ...
    );

    histogram( ...
        'BinCounts',addedControlPre{intervalIndex}, ...
        'BinEdges',controlPreEdges, ...
