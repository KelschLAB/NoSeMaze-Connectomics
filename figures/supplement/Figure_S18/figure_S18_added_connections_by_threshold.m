        'BinCounts',addedConditioningTest{intervalIndex}, ...
        'BinEdges',conditioningTestEdges, ...
        'EdgeColor','none', ...
        'FaceColor',taskTestColor, ...
        'FaceAlpha',0.1, ...
        'LineWidth',1.5 ...
    );

    histogram( ...
        'BinCounts',addedConditioningTest{intervalIndex}, ...
        'BinEdges',conditioningTestEdges, ...
        'EdgeColor',taskTestColor, ...
        'LineWidth',1.5, ...
        'DisplayStyle','stairs' ...
    );

    % Conditioning PRE
    histogram( ...
        'BinCounts',addedConditioningPre{intervalIndex}, ...
        'BinEdges',conditioningPreEdges, ...
        'EdgeColor','none', ...
        'FaceColor',taskPreColor, ...
        'FaceAlpha',0.1, ...
        'LineWidth',1.5 ...
    );

    histogram( ...
        'BinCounts',addedConditioningPre{intervalIndex}, ...
        'BinEdges',conditioningPreEdges, ...
        'EdgeColor',taskPreColor, ...
        'LineWidth',1.5, ...
        'DisplayStyle','stairs' ...
    );

    % Control TEST
    histogram( ...
        'BinCounts',addedControlTest{intervalIndex}, ...
        'BinEdges',controlTestEdges, ...
        'EdgeColor','none', ...
        'FaceColor',controlTestColor, ...
        'FaceAlpha',0.1, ...
        'LineWidth',1.5, ...
